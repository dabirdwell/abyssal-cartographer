"""v4.4: the game names no publisher, and the help button says Help.

On November 10, 2026 the publisher of Shadowdark RPG answered David's note: a Shadowdark integration is not
permitted under its third-party license, and it asked that the game not go on being shared publicly as one.
This version takes that game's name and the license line out of the page. It does so by running
tools/make_neutral.py, which has existed since v3.4 for exactly this answer, so the page that is published
and the page the tests run against are now the same neutral page.

What this version does NOT change is listed at the top of tools/make_neutral.py: the layout of a creature's
stat line, the ladder of difficulties, the real-hour torch and the word "delver" are all still here, under the
name "Old-school". Whether that is enough to meet the publisher's request is David's decision, not this script's.

Also: the button that opens the letter and the first-game steps was called Margins. David ruled it is Help."""
import os, subprocess, sys
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from patchlib import Patch
path = sys.argv[1]
p = Patch(path)

# ---- version ----
p.rep('<span class="ver">v4.3</span>', '<span class="ver">v4.4</span>')
p.rep('<span>v4.3, built 2026-11-10</span>', '<span>v4.4, built 2026-11-10</span>')
p.rep('Generated by Abyssal Cartographer v4.3. Dungeon code: ', 'Generated by Abyssal Cartographer v4.4. Dungeon code: ')
p.rep('Made with Abyssal Cartographer v4.3.', 'Made with Abyssal Cartographer v4.4.', count=2)

# ---- Help ----
p.rep('title="Notes from the Guild of Careful Maps">Margins</button>', 'title="A letter, a step-by-step first game, and the notes in the margins, from the Guild of Careful Maps">Help</button>')
p.rep('The Margins button at the top turns them off whenev', 'The Help button at the top turns them off whenev')
p.save()

# ---- no publisher ----
here = os.path.dirname(os.path.abspath(__file__))
r = subprocess.run([sys.executable, os.path.join(here, 'make_neutral.py'), path, path], capture_output=True, text=True)
print((r.stdout + r.stderr).strip())
if r.returncode != 0: sys.exit('PATCH STOP: the neutral step did not finish')
