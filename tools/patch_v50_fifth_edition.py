"""v5.0: the public game is fifth edition only.

On November 10, 2026 the publisher of the game this tool was first built for asked that an integration with its
game not go on being shared publicly. On November 11 David ruled: the public game is fifth edition only.
This patch takes the other rules out of the page: the rules switch, the second stat-line format, the summary of
those rules handed to an AI game master, experience counted by treasure, that game's light and darkness rules,
its wandering-check rule, and the glossary entries that explained its terms. Fifth edition numbers were already
worked out for every creature; they are now the only numbers. A link that asked for the other rules opens in
fifth edition. A lantern burns six hours on a flask, as the fifth-edition rules say.

Also here, on David's rulings of the same morning: the page says "D&D 5e", and the reading face is EB Garamond
(run tools/embed_fonts.py first; this reads fonts/faces.css).

What this does NOT change, said plainly: each creature's numbers are still stored in the source in the order
they were first written (armor, hit points, attack, movement band, six modifiers, a level), and the fifth
edition numbers are worked out from them when the page runs. No dungeon changes: the same code builds the same
rooms, doors, creatures and treasure."""
import os, re, sys
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from patchlib import Patch
p = Patch(sys.argv[1])
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FACES = open(os.path.join(ROOT, 'fonts', 'faces.css'), encoding='utf-8').read()
def stop(msg): sys.exit('PATCH STOP: ' + msg)
def cut(pattern, new='', count=1, flags=re.S):
    found = len(re.findall(pattern, p.s, flags))
    if found != count: stop('expected %d of /%s/, found %d' % (count, pattern[:80], found))
    p.s = re.sub(pattern, lambda m: new, p.s, flags=flags); p.n += 1

# ---- version ----
p.rep('<span class="ver">v4.4</span>', '<span class="ver">v5.0</span>')
p.rep('<span>v4.4, built 2026-11-10</span>', '<span>v5.0, built 2026-11-11</span>')
p.rep('Generated by Abyssal Cartographer v4.4. Dungeon code: ', 'Generated by Abyssal Cartographer v5.0. Dungeon code: ')
p.rep('Made with Abyssal Cartographer v4.4.', 'Made with Abyssal Cartographer v5.0.', count=2)

# ---- the reading face: EB Garamond ----
cut(r'<style id="faces">\n.*?</style>', '<style id="faces">\n' + FACES + '</style>')
p.rep('--serif:"Alegreya","Iowan Old Style","Palatino Linotype",Palatino,Georgia,serif;', '--serif:"EB Garamond","Iowan Old Style","Palatino Linotype",Palatino,Georgia,serif;')
p.rep("const EXP_CSS=\"body{font-family:'Alegreya','Iowan Old Style',", "const EXP_CSS=\"body{font-family:'EB Garamond','Iowan Old Style',")
p.rep('font-family="Alegreya,Georgia,serif" font-weight="700">N</text>', 'font-family="EB Garamond,Georgia,serif" font-weight="700">N</text>')

# ---- one set of rules: the switch goes, and the page says which rules these are ----
cut(r'  <div class="hgroup">\n    <div class="toggle" id="sysToggle".*?</div>\n  </div>\n',
    '  <span class="rules" title="Dungeons &amp; Dragons 5th edition. The creatures here are original; where one matches a monster you know, use the official numbers.">D&amp;D 5e</span>\n')
p.rep('.brand .star{display:inline-flex; align-self:center}', '.brand .star{display:inline-flex; align-self:center}\nheader .rules{font-family:var(--sans); font-size:14.5px; color:var(--parch-dim); padding:4px 9px; border:1px solid var(--line); border-radius:var(--r-ctl); white-space:nowrap}')
cut(r'\$\("#sysToggle"\)\.addEventListener\("click".*?syncHash\(\);\}\);\n')
cut(r'[ ]*\$\("#sysToggle"\)\.querySelectorAll\("button"\)\.forEach\(x=>x\.classList\.toggle\("on",x\.dataset\.sys===S\.sys\)\);\n', count=2)
p.rep('sel:0,sys:"sd",view:"dm"', 'sel:0,sys:"5e",view:"dm"')
p.rep('sys:p[9]||"sd",view:p[10]||"dm"', 'sys:"5e",view:p[10]||"dm"')
p.rep('sys||"sd","player"', '"5e","player"')
p.rep('sys:p[9]||"sd",rhex:p[11]||""', 'sys:"5e",rhex:p[11]||""')
p.rep('S.sys=msg.sys||"sd";', 'S.sys="5e";')
p.rep('S.sys=a.sys||"sd";', 'S.sys="5e";')
p.rep('S.sys=hp.sys;S.view=hp.view;', 'S.sys="5e";S.view=hp.view;')

# ---- a creature's numbers: fifth edition only, with ranges in feet ----
cut(r'function statText\(m,sys\)\{.*?\n\}\n\nreturn\{generate', '''function statText(m){
  const sc=m.m.map(x=>10+2*x);
  const hp=Math.max(1,Math.round(m.hp*7/4.5));
  const dmg=d=>{const q=String(d).split(","),r=(q[1]||"").trim();return q[0].trim()+(r==="far"?", range 120 ft.":r==="near"?", range 30 ft.":"");};
  const atk=m.atk.map(a=>a.n+" "+fm(a.b+2)+" ("+dmg(a.d)+")").join(" or ");
  return{l1:"AC "+m.ac+", HP "+hp+", Speed "+mv5e(m.mv),
    l2:"STR "+sc[0]+" DEX "+sc[1]+" CON "+sc[2]+" INT "+sc[3]+" WIS "+sc[4]+" CHA "+sc[5]+", CR "+(LV2CR[m.lv]||m.lv),
    l3:"ATK "+atk};
}

return{generate''')
p.rep('''(S.sys==="sd"?"old-school":"5e")+' stats)''', '''"5e"+' stats)''')
p.rep('''var hp = S.sys==="5e" ? Math.max(1,Math.round(m.hp*7/4.5)) : m.hp;''', '''var hp = Math.max(1,Math.round(m.hp*7/4.5));''')
p.rep('''var ab = S.sys==="5e" ? a.b+2 : a.b;''', '''var ab = a.b+2;''')
p.rep('''var who = S.sys==="5e" ? "character" : "delver";''', '''var who = "character";''')
p.rep('''(String(a.d).indexOf(",")>0?', and it can strike from '+esc(String(a.d).split(",").slice(1).join(",").trim())+' away':'')''',
      '''(/,\\s*far/.test(String(a.d))?', and it can strike from 120 feet away':/,\\s*near/.test(String(a.d))?', and it can strike from 30 feet away':'')''')
p.rep('''          .replace(/\\bMV\\b/g,'<span class="qterm" data-q="mv">MV</span>')\n''', '')
p.rep('''          .replace(/\\bLV\\b/g,'<span class="qterm" data-q="lv">LV</span>')\n''', '')
p.rep('''          .replace(/\\bAL\\b/g,'<span class="qterm" data-q="al">AL</span>')\n''', '')

# ---- experience: fifth edition's way only ----
p.rep('''(S.sys==="sd"?"Treasure is experience. Each hoard carried out is worth XP by its rating.":"In 5e, experience comes from foes overcome, not from coin.")''', '''"In fifth edition, experience comes from foes overcome, not from coin."''')
cut(r'    if\(S\.sys==="sd"\)\{var HB=hoardXP\(\);\n.*?</div>\';\}\n')
p.rep('''+(S.sys==="sd"?' Carouse to spend it and roll on your table of regrets.':'')+''', '+')
cut(r'function hoardXP\(\)\{.*?\n\}\n')
cut(r'''  var H=hoardXP\(\);\n  \$\("#xpFoot"\)\.innerHTML= S\.role==="player" \? '◆ Your game master keeps track of treasure and points\.' : S\.sys==="sd"\n    \? [^\n]*\n    : ''',
    '''  $("#xpFoot").innerHTML= S.role==="player" ? '◆ Your game master keeps track of treasure and points.'\n    : ''')
cut(r' xp:\["Treasure as experience",[^\n]*\]\n', ' xp:["Experience","In fifth edition, experience comes from what the party overcomes: creatures defeated and, if you like, dangers survived and goals reached. The treasure still matters. It is why anyone comes down here."]\n')
cut(r'[ ]*if\(key==="xp"&&S\.sys==="5e"\)d=\[.*?\];\n')
pat = r'''  steps\.push\(S\.sys==="5e"\?\{t:"How they grow",h:(.*?)\}:\{t:"Gold is how they grow",h:.*?Both are features\.</div>'\}\);'''
m = re.findall(pat, p.s, re.S)
if len(m) != 1: stop('the two "how they grow" steps')
p.s = re.sub(pat, lambda g: '  steps.push({t:"How they grow",h:' + g.group(1) + '});', p.s, flags=re.S); p.n += 1
p.rep('''+(S.sys==="5e"?' In fifth edition this is a house rule; keep it if you like the pressure.':'')+''', '''+' Counting it in real time is a house rule; keep it if you like the pressure.'+''')
p.rep('''  if(S.sys==="5e")steps.forEach(function(s){s.t=sysWords(s.t);s.h=sysWords(s.h);});''', '''  steps.forEach(function(s){s.t=sysWords(s.t);s.h=sysWords(s.h);});''')
p.rep('''  if(S.sys!=="5e")return s;\n''', '')

# ---- the glossary: the entries that explained the other game's terms go; the rest speak fifth edition ----
cut(r' mv:\["Movement",[^\n]*\],\n')
cut(r' lv:\["Level",[^\n]*\],\n')
cut(r' al:\["Alignment",[^\n]*\],\n')
cut(r' range:\["Close, near, far",[^\n]*\],\n')
p.rep(''' ac:["Armour Class","The number a delver must meet or beat''', ''' ac:["Armor Class","The number an attacker must meet or beat''')
p.rep(''' cr:["Challenge Rating","The other system's way of saying the same thing. A guess at how much fight it is."],''', ''' cr:["Challenge Rating","A rough weight of trouble. Set it beside your party's level and you will know whether to be worried."],''')
cut(r' delver:\["Delver",[^\n]*\],\n', ''' delver:["Adventurers","The players' characters. People who go down into places like this on purpose. You are not one of them; you are the one holding the map."],\n''')

# ---- light and dark, by the fifth-edition rules ----
p.rep('const SRC={torch:3600,lantern:3600,candle:3600,spell:3600};', 'const SRC={torch:3600,lantern:21600,candle:3600,spell:3600};')
p.rep('<option value="lantern">Lantern (1 hr per oil flask)</option>', '<option value="lantern">Lantern (6 hr per flask of oil)</option>')
p.rep('<option value="candle">Candle (1 hr, close; a house addition)</option>', '<option value="candle">Candle (1 hr, a small light)</option>')
p.rep('You are in the dark. Disadvantage on tasks and attacks. Foes with darksight have advantage.', 'You are in the dark. Without darkvision you cannot see: your attacks have disadvantage, and attacks against you have advantage.')
cut(r'''  h\+='<h2>Light, by the Real Clock'\+\(S\.sys==="5e"\?' \(a house rule, optional in 5e\)':''\)\+'</h2><table>.*?</table><p class="tiny">In darkness:[^<]*</p>';\n''',
    '''  h+='<h2>Light</h2><table><tr><th>Source</th><th>Burns</th><th>Bright light, then dim</th></tr><tr><td>Torch</td><td>1 hour</td><td>20 feet, then 20 more</td></tr><tr><td>Lantern, hooded</td><td>6 hours on a flask of oil</td><td>30 feet, then 30 more</td></tr><tr><td>Candle</td><td>1 hour</td><td>5 feet, then 5 more</td></tr><tr><td>The light cantrip</td><td>1 hour</td><td>20 feet, then 20 more</td></tr></table><p class="tiny">The torch clock on the screen counts these in real time. That is a house rule; keep it if you like the pressure. In darkness, a creature without darkvision cannot see: its attacks have disadvantage, and attacks against it have advantage.</p>';\n''')
p.rep('Roll 1d6 between crawling rounds; an encounter arrives on a 1. How often you roll is set by how dangerous the place is: unsafe, every third round. Risky, every second. Deadly, every round. Roll as well whenever the party makes a loud disturbance, whatever the count says.',
      'Roll 1d6 for every ten minutes or so the party spends exploring, and whenever they make a loud disturbance. An encounter arrives on a 1.')

# ---- the notes for whoever runs it, human or otherwise ----
p.rep(',five=S.sys==="5e";', ',five=true;')
cut(r'  const rules=five\n    \?".*?"\n    :".*?";\n',
    '''  const rules="Dungeons & Dragons 5th edition, the SRD rules you know. Where a creature below matches a standard 5e monster (skeleton, zombie, giant rat, giant spider, giant centipede, acolyte, cult fanatic, wight, ooze and so on), use the official stat block and treat the numbers here only as a guide to its strength";\n''')
p.rep('''  if(S.sys==="5e")h+='<div class="klabel">No character yet?</div>''', '''  h+='<div class="klabel">No character yet?</div>''')
p.rep('''Rules: <b>'+(S.sys==="5e"?"Fifth edition":"Old-school rules")+'</b>. '+(S.sys==="5e"?"AI game masters know fifth edition best, so it is the default here. Switch to Old-school at the top if you play a rules-light dungeon game.":"Switch to 5e at the top if you would rather play that; AI game masters know it best.")+'</div>';''',
      '''Rules: <b>Dungeons &amp; Dragons 5th edition</b>. If you have never played, your game master will teach you as you go.</div>';''')

# ---- what is left over once nothing counts treasure as experience ----
cut(r'/\* Experience is awarded by treasure hoard tier.*?function sdXP\(gp,kind\)\{return sdTier\(gp,kind\)\.xp;\}\n')
p.rep('bestiary (old-school native, original text)', 'bestiary (original text)')
p.rep('stat text: old-school native, 5e projection', 'stat text: fifth edition')
p.rep("/* In 5e mode, the old-school words step aside. Text only. */", '/* The page says adventurers. Text only. */')

# one treasure's wording used the other game's word for a distance. The generator is left alone, so an old code
# still builds the same dungeon; the page puts the distance in feet when it takes the dungeon in.
p.rep('const CAP=s=>String(s).charAt(0).toUpperCase()+String(s).slice(1);', '''const CAP=s=>String(s).charAt(0).toUpperCase()+String(s).slice(1);
const feet5=m=>{m.rooms.forEach(r=>r.treasure.forEach(t=>{t.txt=String(t.txt).replace("within near range","within 30 feet");}));return m;};''')
p.rep('  S.model=AC.generate(cfg);', '  S.model=feet5(AC.generate(cfg));')
p.rep('  S.model=AC.generate({seed:cfg.seed,', '  S.model=feet5(AC.generate({seed:cfg.seed,')
p.rep('origin:cfg.origin,doom:cfg.doom});', 'origin:cfg.origin,doom:cfg.doom}));')
p.rep('treasure worth XP, and a real-time torch', 'treasure, and a torch that burns in real time')
pat2 = r'What they carry out is what they learn from\.(</b>|</strong>)? Gold hauled back to town becomes experience\.'
if len(re.findall(pat2, p.s)) != 1: stop('the letter\'s line about gold and experience')
p.s = re.sub(pat2, lambda g: 'What they overcome is what they learn from.' + (g.group(1) or '') + ' In fifth edition, experience comes from foes defeated and dangers survived. The gold is why anyone comes down here.', p.s); p.n += 1
p.rep('<button data-tab="loot">Treasure &amp; XP</button>', '<button data-tab="loot">Treasure</button>')
p.rep('Your delvers arrive as a fourth problem.', 'Your adventurers arrive as a fourth problem.')

# ---- the settings and the page's own description ----
p.rep('<label>Party level<span class="hint">Levels 0 to 9</span></label><select id="cfgLevel"><option>0</option><option selected>1</option>', '<label>Party level</label><select id="cfgLevel"><option selected>1</option>')
p.rep('Old-school stats for rules-light dungeon games, with classic 5e stats included.', 'Fifth edition numbers for every creature.')
p.save()

left = sorted(set(re.findall(r'.{0,70}(?:[Oo]ld-school|hoardXP|sdXP|[Cc]arous|darksight|crawling round|S\.sys===?"sd"|data-sys=|sysToggle|Shadowdark|Arcane Library).{0,50}', p.s)))
if left: sys.exit('FIFTH EDITION STOP: the other rules are still here:\n' + '\n'.join(left))
